type MetricsDictType = dict[str, float | int | str]
"""Type used to represent dictionaries of evaluation metrics."""
type InvocableModelChain = langchain_core.runnables.Runnable[typing.Any, typing.Any]
"""Type used to represent invocable model chains (i.e. objects with an 'invoke' method)."""
type TokenUsageMapping = collections.abc.Mapping[str, typing.Any]
"""Type used for mapping-like containers that expose token usage information."""
type TokenCount = int | typing.Literal["unknown"]
"""Type used to represent token counts, either as an integer or the literal string "unknown"."""
TokenType = typing.Literal[
    "total_tokens",
    "prompt_tokens",
    "cached_tokens",
    "reasoning_tokens",
    "completion_tokens",
]
"""Type used to represent token counts that can be used as keys in a MetricsDictType."""


@dataclasses.dataclass
class TokenUsageInfo:
    """Unified token usage information across multiple provider response formats.

    Supports some arithmetic operations that perform field-wise sums. In those operations, if
    both operands have 'unknown' for a field, the result is 'unknown' for that field. If one
    operand has an int and the other has 'unknown' for a field, raises ValueError.
    """

    total_tokens: TokenCount
    """Total number of tokens exchanged with the LLM (input + output)."""
    prompt_tokens: TokenCount
    """Number of tokens used in the input prompt provided to the LLM."""
    cached_tokens: TokenCount
    """Number of cached tokens used in the input prompt provided to the LLM."""
    reasoning_tokens: TokenCount
    """Number of tokens used in the reasoning generated by the LLM."""
    completion_tokens: TokenCount
    """Number of tokens used in the completion (answer) provided by the LLM."""

    @staticmethod
    def _combine_field(a: TokenCount, b: TokenCount, field_name: str) -> TokenCount:
        """Helper to combine two token counts, raising ValueError if they cannot be combined."""
        if isinstance(a, int) and isinstance(b, int):
            return a + b
        if a == "unknown" and b == "unknown":
            return "unknown"
        raise ValueError(f"cannot combine token field '{field_name}': mixed known and 'unknown' values")

    def __add__(self, other: typing.Any) -> "TokenUsageInfo":
        """Add two TokenUsageInfo objects together, returning a new object with the result."""
        if self == self.get_default():
            return other
        if other == self.get_default():
            return self
        return TokenUsageInfo(
            **typing.cast(
                "dict[str, TokenCount]",
                {t: self._combine_field(getattr(self, t), getattr(other, t), t) for t in typing.get_args(TokenType)},
            )
        )

    def __iadd__(self, other: typing.Any) -> "TokenUsageInfo":
        """Add two TokenUsageInfo objects together, in-place."""
        if other == self.get_default():
            return self
        if self == self.get_default():
            for token_type in typing.get_args(TokenType):
                setattr(self, token_type, getattr(other, token_type))
            return self
        for token_type in typing.get_args(TokenType):
            setattr(
                self,
                token_type,
                self._combine_field(getattr(self, token_type), getattr(other, token_type), token_type),
            )
        return self

    @classmethod
    def get_default(cls) -> "TokenUsageInfo":
        """Returns a TokenUsageInfo object with all fields set to unknown."""
        return cls(**typing.cast("dict[str, TokenCount]", dict.fromkeys(typing.get_args(TokenType), "unknown")))

    @staticmethod
    def get_metric_names() -> list[str]:
        """Returns a list of metric names supported by this evaluator."""
        return list(typing.get_args(TokenType))

    def asdict(self) -> dict[str, TokenCount]:
        """Returns a dictionary representation of the TokenUsageInfo object."""
        return {t: getattr(self, t) for t in typing.get_args(TokenType)}


def parse_token_usage_from_response(
    response: typing.Any,
) -> TokenUsageInfo:
    """Parse token usage fields from an LLM response coming from various sources.

    This function namely supports:
      - dict-like responses that include a "usage" section
      - OpenAI Chat Completions objects (duck-typed via `.usage` attribute)
      - OpenAI Responses API objects (duck-typed via `.usage` attribute)
      - PromptResultRecord-like objects whose raw response is available at
        `obj.creation_meta.llm_output` (either attribute or dict key)

    The extracted fields will be returned in a unified structure. Fields that cannot be determined
    are set to the literal string "unknown". If no usage-related field can be determined at all,
    a ValueError is raised.

    Args:
        response: Provider response or wrapper object.

    Returns:
        A TokenUsageInfo mapping populated with any discovered counts and "unknown" defaults.

    Raises:
        ValueError: If token usage information cannot be deduced from the given response.
    """

    def _get_usage_mapping(
        obj: typing.Any,
    ) -> typing.Any:
        # try '.usage' and '.token_usage' attributes/mappings first (openai-like objects expose those)
        attribs_to_check = ["usage", "usage_metadata", "token_usage"]
        for check_attrib in attribs_to_check:
            if hasattr(obj, check_attrib):
                return getattr(obj, check_attrib)
        if isinstance(obj, collections.abc.Mapping):
            mapping_obj = typing.cast("TokenUsageMapping", obj)
            for check_attrib in attribs_to_check:
                if check_attrib in mapping_obj:
                    return mapping_obj[check_attrib]
        # if it's a PromptResultRecord-like object, dig into creation_meta.llm_output
        # (support both attribute-style and dict-style access for creation_meta)
        if isinstance(obj, collections.abc.Mapping):
            mapping_obj = typing.cast("TokenUsageMapping", obj)
            creation_meta = mapping_obj.get("creation_meta")
        else:
            creation_meta = getattr(obj, "creation_meta", None)
        if creation_meta is not None:
            inner = getattr(creation_meta, "llm_output", None)
            if inner is None and isinstance(creation_meta, collections.abc.Mapping):
                creation_meta_mapping = typing.cast("TokenUsageMapping", creation_meta)
                inner = creation_meta_mapping.get("llm_output", None)
            if inner is not None:
                return _get_usage_mapping(inner)
        # some callers might directly pass the raw llm_output dict
        if isinstance(obj, collections.abc.Mapping):
            # sometimes the raw llm output might be nested under a known key
            mapping_obj = typing.cast("TokenUsageMapping", obj)
            for key in ("llm_output", "raw", "response"):
                if key in mapping_obj and mapping_obj[key] is not None:
                    return _get_usage_mapping(mapping_obj[key])
        return None

    def _maybe_get_number(
        container: typing.Any,
        name: str,
    ) -> int | None:
        if container is None:
            return None
        name_parts = name.split(".")
        subcontainer_names, name = name_parts[:-1], name_parts[-1]
        for subcontainer_name in subcontainer_names:
            # try both attribute access and mapping access to get the real container
            if hasattr(container, subcontainer_name):
                container = getattr(container, subcontainer_name)
            elif isinstance(container, dict) and subcontainer_name in container:
                typed_container = typing.cast("dict[str, typing.Any]", container)
                container = typed_container.get(subcontainer_name)
            else:
                return None  # failed to get expected subcontainer
        # try both attribute access and mapping access for the targeted value
        if hasattr(container, name):
            val = getattr(container, name)
            if isinstance(val, (int, float)) and not isinstance(val, bool):
                return int(val)
        if isinstance(container, dict) and name in container:
            typed_container = typing.cast("dict[str, typing.Any]", container)
            val = typed_container.get(name)
            if isinstance(val, (int, float)) and not isinstance(val, bool):
                return int(val)
        return None

    def _get_first_available(
        container: typing.Any,
        names: list[str],
    ) -> int | None:
        for name in names:
            val = _maybe_get_number(container, name)
            if val is not None:
                return val
        return None

    usage = _get_usage_mapping(response)
    result: TokenUsageInfo = TokenUsageInfo.get_default()
    total_kws = ["total_tokens", "total"]
    if (total := _get_first_available(usage, total_kws)) is not None:
        result.total_tokens = total
    prompt_kws = ["prompt_tokens", "input_tokens"]
    if (prompt := _get_first_available(usage, prompt_kws)) is not None:
        result.prompt_tokens = prompt
    cached_kws = [
        "prompt_tokens_details.cached_tokens",
        "input_token_details.cache_read",
        "cached_tokens",
    ]
    if (cached := _get_first_available(usage, cached_kws)) is not None:
        result.cached_tokens = cached
    reasoning_kws = [
        "completion_tokens_details.reasoning_tokens",
        "output_token_details.reasoning",
        "reasoning_tokens",
        "thinking_tokens",
    ]
    if (reasoning := _get_first_available(usage, reasoning_kws)) is not None:
        result.reasoning_tokens = reasoning
    completion_kws = ["completion_tokens", "output_tokens"]
    if (completion := _get_first_available(usage, completion_kws)) is not None:
        result.completion_tokens = completion
    any_known = any(isinstance(getattr(result, token_type), int) for token_type in typing.get_args(TokenType))
    if not any_known:
        raise ValueError("could not deduce token usage information from the provided response")
    return result


def print_metrics(
    metrics: MetricsDictType,
    subset: str | None = None,
    logger: typing.Callable[[str], typing.Any] | None = None,
) -> None:
    """Helper that prints the given metrics using the provided callable logger (or stdout)."""
    eval_output_strs: list[str] = []
    for key, val in metrics.items():
        if isinstance(val, float):
            eval_output_strs.append(f"\t{key}: {val:.3f}")
        elif isinstance(val, int):
            eval_output_strs.append(f"\t{key}: {val:,}")
        else:
            eval_output_strs.append(f"\t{key}: {val}")
    eval_output_str = "\n".join(eval_output_strs)
    output_str = f"metrics:\n{eval_output_str}" if subset is None else f"{subset} metrics:\n{eval_output_str}"
    if logger is None:
        print(output_str)
    else:
        logger(output_str)


class CategoryWiseMetricsCallback(transformers.TrainerCallback):
    """Streams evaluation metrics without materializing full prediction arrays.

    This callback accumulates per-example losses on a category basis as evaluation batches are
    processed. It exposes a callable interface compatible with Hugging Face's ``compute_metrics``
    API (including the ``batch_eval_metrics`` flow) while also integrating with the callback
    system to print and log aggregated metrics once an evaluation loop completes.
    """

    def __init__(
        self,
        data_sample_categories: list[list[str]],
        ignore_index: int = pyine.utils.transformers.default_ignore_index,
        log_fn: collections.abc.Callable[[str], typing.Any] | None = None,
    ) -> None:
        """Initialize the callback."""
        self.data_sample_categories = data_sample_categories
        self.ignore_index = ignore_index
        self._log_fn = log_fn
        self._expected_examples = len(data_sample_categories)
        self._latest_metrics: MetricsDictType = {}
        self._has_active_eval = False
        self._category_loss_sums: collections.defaultdict[str, float]
        self._category_counts: collections.defaultdict[str, int]
        self._processed_examples = 0
        self._reset_accumulators()

    def _reset_accumulators(
        self,
    ) -> None:
        """Clear all per-evaluation accumulators."""
        self._category_loss_sums = collections.defaultdict(float)
        self._category_counts = collections.defaultdict(int)
        self._processed_examples = 0

    def _ensure_eval_started(
        self,
    ) -> None:
        """Prepare accumulators when a new evaluation loop begins."""
        if self._has_active_eval:
            return
        self._reset_accumulators()
        self._latest_metrics = {}
        self._has_active_eval = True

    def _update_from_batch(
        self,
        logits_tensor: torch.Tensor,
        labels_tensor: torch.Tensor,
        batch_categories: list[list[str]],
    ) -> None:
        """Update accumulators using a single evaluation batch."""
        if logits_tensor.ndim != 3 or labels_tensor.ndim != 2:
            raise ValueError(f"unexpected tensor shapes: logits={logits_tensor.shape} labels={labels_tensor.shape}")
        if logits_tensor.shape[0] != labels_tensor.shape[0]:
            raise ValueError(f"unexpected batch sizes: logits={logits_tensor.shape[0]} labels={labels_tensor.shape[0]}")
        if logits_tensor.shape[0] != len(batch_categories):
            raise ValueError(
                f"batch categories mismatch: expected {logits_tensor.shape[0]} items, got {len(batch_categories)}"
            )
        shift_logits = logits_tensor[:, :-1, :].contiguous()
        shift_labels = labels_tensor[:, 1:].contiguous()
        # we should probably be doing this on GPU to keep things fast...
        per_token_loss = torch.nn.functional.cross_entropy(
            shift_logits.view(-1, shift_logits.size(-1)),
            shift_labels.view(-1).long(),
            reduction="none",
            ignore_index=self.ignore_index,
        )
        per_token_loss = per_token_loss.view(shift_labels.shape)
        loss_mask = shift_labels.ne(self.ignore_index)
        token_counts = loss_mask.sum(dim=1)
        valid_example_mask = token_counts > 0
        if not bool(valid_example_mask.any()):
            raise ValueError("no valid tokens encountered in current evaluation batch (bad data??)")
        token_loss_sums = (per_token_loss * loss_mask).sum(dim=1)
        per_example_loss = torch.zeros_like(token_loss_sums, dtype=torch.float32)
        per_example_loss[valid_example_mask] = token_loss_sums[valid_example_mask] / token_counts[
            valid_example_mask
        ].to(torch.float32)
        per_example_loss_cpu = per_example_loss.detach().cpu()
        per_example_loss_list: list[float] = [float(val) for val in per_example_loss_cpu]
        for example_idx, loss_value in enumerate(per_example_loss_list):
            categories = batch_categories[example_idx]
            if not categories:
                continue
            for category in categories:
                self._category_loss_sums[category] += loss_value
                self._category_counts[category] += 1

    def get_aggregated_metrics(
        self,
    ) -> MetricsDictType:
        """Return the aggregated category-wise metrics accumulated so far."""
        metrics: MetricsDictType = {}
        for category in sorted(self._category_loss_sums.keys()):
            count = self._category_counts[category]
            if count <= 0:
                continue
            loss_sum = self._category_loss_sums[category]
            metrics[f"{category}/loss"] = loss_sum / count
            metrics[f"{category}/count"] = count
        return metrics

    def define_metrics(
        self,
        wandb_run: wandb.Run,
    ) -> None:
        """Define metrics for wandb logging."""
        known_categories = {cat for sample_cats in self.data_sample_categories for cat in sample_cats}
        for category in known_categories:
            wandb_run.define_metric(  # type: ignore[reportUnknownMemberType]
                f"eval/{category}/loss",
                summary="min",
            )
            wandb_run.define_metric(  # type: ignore[reportUnknownMemberType]
                f"eval/{category}/count",  # is actually static, that's why we hide it
                hidden=True,
                summary="none",
            )

    def _log_metrics(
        self,
        metrics: MetricsDictType,
    ) -> None:
        """Log metrics to stdout/logger."""
        if not metrics:
            return
        print_metrics(metrics=metrics, logger=self._log_fn)

    def __call__(
        self,
        eval_prediction: transformers.trainer_utils.EvalPrediction,
        compute_result: bool = False,
        **_: typing.Any,
    ) -> MetricsDictType:
        """Consume a batch of predictions coming from the trainer."""
        self._ensure_eval_started()
        logits_tensor = torch.as_tensor(eval_prediction.predictions)
        labels_tensor = torch.as_tensor(eval_prediction.label_ids)
        start_idx = self._processed_examples
        batch_size = logits_tensor.shape[0]
        end_idx = start_idx + batch_size
        if end_idx > self._expected_examples:
            raise ValueError(f"received {end_idx} evaluation samples but only {self._expected_examples} were expected")
        batch_categories = self.data_sample_categories[start_idx:end_idx]
        self._update_from_batch(
            logits_tensor=logits_tensor,
            labels_tensor=labels_tensor,
            batch_categories=batch_categories,
        )
        self._processed_examples = end_idx
        is_final = compute_result or self._processed_examples == self._expected_examples
        if not is_final:
            return {}
        if self._processed_examples != self._expected_examples:
            raise ValueError(f"processed {self._processed_examples} examples, expected {self._expected_examples}")
        self._latest_metrics = self.get_aggregated_metrics()
        self._has_active_eval = False
        return dict(self._latest_metrics)

    @typing.override
    def on_evaluate(
        self,
        args: transformers.TrainingArguments,
        state: transformers.trainer_callback.TrainerState,
        control: transformers.trainer_callback.TrainerControl,
        **kwargs: typing.Any,
    ) -> None:
        """Log aggregated metrics and reset state after evaluation."""
        _ = kwargs.get("metrics")
        aggregated = dict(self._latest_metrics) if self._latest_metrics else self.get_aggregated_metrics()
        self._log_metrics(aggregated)
        self._latest_metrics = {}
        self._has_active_eval = False
        self._reset_accumulators()


def build_category_wise_compute_metrics_fn(
    data_sample_categories: list[list[str]],
    ignore_index: int = pyine.utils.transformers.default_ignore_index,
    log_fn: collections.abc.Callable[[str], typing.Any] | None = None,
    runtime: pyine.configs.schemas.RuntimeConfig | None = None,
) -> CategoryWiseMetricsCallback:
    """Build a streaming evaluation callback for category-wise metrics.

    Note: for this callback to work, the HuggingFace Trainer must be initialized with the
    `batch_eval_metrics` trainer argument, and the callback object returned by this function
    must be passed to the Trainer's `compute_metrics` argument as well as inside its `callbacks`
    list.
    """
    callback = CategoryWiseMetricsCallback(
        data_sample_categories=data_sample_categories,
        ignore_index=ignore_index,
        log_fn=log_fn,
    )
    if runtime is not None and runtime.wandb_run is not None:
        callback.define_metrics(runtime.wandb_run)
    return callback


class SampleCategoryField(enum.StrEnum):
    """Fields from SampleData that can be used as category sources for metrics."""

    code_type = enum.auto()
    """Extract categories from the code_type field (frozenset of SampleCodeType)."""
    tags = enum.auto()
    """Extract categories from comma_separated_tags field, split by prefix."""
    predict_type = enum.auto()
    """Extract categories from the predict_type field (SamplePredictType enum)."""
    has_code_override = enum.auto()
    """Extract categories from the has_code_override boolean field."""


class SampleCategoryExtractionConfig(pydantic.BaseModel):
    """Configuration for extracting sample categories from dataset fields.

    This configuration controls which SampleData fields are used to generate category labels
    for category-wise metrics during evaluation.
    """

    model_config = pydantic.ConfigDict(frozen=True, extra="forbid")

    enabled_fields: frozenset[SampleCategoryField] = pydantic.Field(
        default=frozenset({SampleCategoryField.code_type, SampleCategoryField.predict_type}),
        description="Set of fields to extract categories from.",
    )
    tag_prefixes: frozenset[str] | None = pydantic.Field(
        default=None,
        description=(
            "When extracting from tags field, only include tags with these prefixes. "
            "If None, all tag prefixes are included. Example: {'augment', 'subset'}."
        ),
    )


class SampleCategoryExtractor:
    """Extracts category labels from SampleData fields for metrics tracking.

    This class handles the conversion of various SampleData field types into string category
    labels suitable for CategoryWiseMetricsCallback.
    """

    def __init__(
        self,
        config: SampleCategoryExtractionConfig,
    ) -> None:
        """Initialize the extractor with the given configuration.

        Args:
            config: Configuration specifying which fields to extract and how.
        """
        self._config = config

    def extract_categories(
        self,
        sample_data: typing.Mapping[str, typing.Any],
    ) -> list[str]:
        """Extract category labels from a single sample's data.

        Args:
            sample_data: Dictionary containing sample fields (from SampleData).

        Returns:
            List of category strings for this sample.
        """
        categories: list[str] = []
        for field in self._config.enabled_fields:
            field_categories = self._extract_field_categories(sample_data, field)
            categories.extend(field_categories)
        return categories

    def _extract_field_categories(
        self,
        sample_data: typing.Mapping[str, typing.Any],
        field: SampleCategoryField,
    ) -> list[str]:
        """Extract categories from a specific field."""
        if field == SampleCategoryField.code_type:
            return self._extract_code_type_categories(sample_data)
        if field == SampleCategoryField.tags:
            return self._extract_tag_categories(sample_data)
        if field == SampleCategoryField.predict_type:
            return self._extract_predict_type_categories(sample_data)
        if field == SampleCategoryField.has_code_override:
            return self._extract_has_code_override_categories(sample_data)
        return []

    def _extract_code_type_categories(
        self,
        sample_data: typing.Mapping[str, typing.Any],
    ) -> list[str]:
        """Extract categories from code_type field."""
        code_type = sample_data.get("code_type")
        if code_type is None:
            return []
        if isinstance(code_type, str):
            return [f"{SampleCategoryField.code_type.value}/{code_type}"]
        if isinstance(code_type, (frozenset, set, list, tuple)):
            code_type_iterable = typing.cast("typing.Iterable[typing.Any]", code_type)
            type_values = sorted(str(t) for t in code_type_iterable)
            combined = "_".join(type_values) if type_values else None
            if combined:
                return [f"{SampleCategoryField.code_type.value}/{combined}"]
        return []

    def _extract_tag_categories(
        self,
        sample_data: typing.Mapping[str, typing.Any],
    ) -> list[str]:
        """Extract categories from comma_separated_tags field.

        Tags are parsed by prefix (e.g., "augment:type" -> "tags/augment/type").
        """
        tags_str = sample_data.get("comma_separated_tags")
        if not tags_str or not isinstance(tags_str, str):
            return []
        categories: list[str] = []
        for tag in tags_str.split(","):
            tag = tag.strip()
            if not tag:
                continue
            if ":" in tag:
                prefix, value = tag.split(":", maxsplit=1)
                if self._config.tag_prefixes is not None and prefix not in self._config.tag_prefixes:
                    continue
                category_value = f"{prefix}/{value}"
            else:
                if self._config.tag_prefixes is not None:
                    continue  # skip non-prefixed tags when filtering
                category_value = tag
            categories.append(f"{SampleCategoryField.tags.value}/{category_value}")
        return categories

    def _extract_predict_type_categories(
        self,
        sample_data: typing.Mapping[str, typing.Any],
    ) -> list[str]:
        """Extract categories from predict_type field."""
        predict_type = sample_data.get("predict_type")
        if predict_type is None:
            return []
        if isinstance(predict_type, str):
            return [f"{SampleCategoryField.predict_type.value}/{predict_type}"]
        type_value = getattr(predict_type, "value", str(predict_type))
        return [f"{SampleCategoryField.predict_type.value}/{type_value}"]

    def _extract_has_code_override_categories(
        self,
        sample_data: typing.Mapping[str, typing.Any],
    ) -> list[str]:
        """Extract categories from has_code_override boolean field."""
        has_override = sample_data.get("has_code_override")
        if has_override is None:
            return []
        value = "true" if has_override else "false"
        return [f"{SampleCategoryField.has_code_override.value}/{value}"]


def extract_sample_categories_from_dataset(
    dataset: typing.Any,
    config: SampleCategoryExtractionConfig | None = None,
) -> list[list[str]]:
    """Return the list of evaluation categories for each example in a dataset.

    The returned list has the same length as the dataset, where each element is a list of
    category strings associated with the corresponding example.

    Args:
        dataset: HuggingFace dataset with a 'sample_data' column.
        config: Configuration for category extraction. If None, uses default configuration
            (backward compatible: code_type only, no field prefix).

    Returns:
        List of category lists, one per dataset example.
    """
    if dataset is None or not hasattr(dataset, "__len__"):
        return []
    if not hasattr(dataset, "column_names") or "sample_data" not in dataset.column_names:
        return []
    if config is None:
        config = SampleCategoryExtractionConfig()
    extractor = SampleCategoryExtractor(config)
    sample_column = dataset["sample_data"]
    if isinstance(sample_column, dict):
        sample_column_mapping = typing.cast("typing.Mapping[str, typing.Any]", sample_column)
        return _extract_categories_from_dict_column(sample_column_mapping, extractor, len(dataset))
    return _extract_categories_from_sequence_column(sample_column, extractor)


def _extract_categories_from_dict_column(
    sample_column: typing.Mapping[str, typing.Any],
    extractor: SampleCategoryExtractor,
    dataset_len: int,
) -> list[list[str]]:
    """Extract categories when sample_data is accessed as a dict of arrays."""
    results: list[list[str]] = []
    for idx in range(dataset_len):
        sample_data: dict[str, typing.Any] = {}
        for key, values in sample_column.items():
            if hasattr(values, "__getitem__") and len(values) > idx:
                sample_data[key] = values[idx]
        categories = extractor.extract_categories(sample_data)
        results.append(categories)
    return results


def _extract_categories_from_sequence_column(
    sample_column: typing.Iterable[typing.Any],
    extractor: SampleCategoryExtractor,
) -> list[list[str]]:
    """Extract categories when sample_data is accessed as a sequence of dicts."""
    results: list[list[str]] = []
    for sample_data in sample_column:
        if isinstance(sample_data, dict):
            sample_data_mapping = typing.cast("typing.Mapping[str, typing.Any]", sample_data)
            categories = extractor.extract_categories(sample_data_mapping)
        else:
            categories = []
        results.append(categories)
    return results
