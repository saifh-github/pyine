"""DataModule for correctness evaluations based on LMDB pregenerated eval records."""

from __future__ import annotations

import collections
import logging
import pathlib  # noqa: TC003
import typing

import datasets

import pyine.data.datamodule
import pyine.data.utils.lmdb_io
import pyine.evals.correctness.data_loading as correctness_data_loading
import pyine.evals.correctness.splits as correctness_splits
import pyine.evals.correctness.types as correctness_types
import pyine.utils.reprod

if typing.TYPE_CHECKING:
    from pyine.evals.correctness.datamodule_configs import CorrectnessDataModuleConfig

logger = logging.getLogger(__name__)


class CorrectnessDataModule(pyine.data.datamodule.BaseDataModule["CorrectnessDataModuleConfig"]):
    """DataModule for correctness evaluation on LMDB eval records.

    The LMDB datasets used by this datamodule are expected to be generated by the code execution
    evaluation pipeline; the records contain generated outputs by models that could be correct or
    incorrect, and that guardrails must analyze as input.

    This datamodule interface provides the ``prepare_data()`` -> ``setup()`` lifecycle expected by
    the `pyine.apps.trainers.common.evaluate_model` pipeline, but only implements the basic
    datamodule components needed; trying to access traditional train/valid/test dataloaders will
    fail. Instead, primary accessors are `get_guardrail_splits`, `get_records_for_subset`,
    `get_all_records`, and `get_hf_dataset_dict`.
    """

    def __init__(self, config: CorrectnessDataModuleConfig) -> None:
        """Initialize the datamodule with the given configuration."""
        super().__init__(config)
        self._resolved_lmdb_paths: list[pathlib.Path] | None = None
        self._all_records: list[correctness_types.EvalRecord] | None = None
        self._guardrail_splits: correctness_splits.GuardrailSplits | None = None

    @typing.override
    def prepare_data(self) -> None:
        """Resolve, validate, and deduplicate LMDB paths.

        Uses :func:`~pyine.data.utils.lmdb_io.resolve_lmdb_paths` to expand glob patterns,
        auto-discover rank subdirectories, and validate that each resolved path is an LMDB
        directory containing ``data.mdb``. Fast check only (no data loading); matches Lightning
        convention of download/verify in ``prepare_data``, load in ``setup``.
        """
        self._resolved_lmdb_paths = pyine.data.utils.lmdb_io.resolve_lmdb_paths(self.config.lmdb_paths)

    @typing.override
    def setup(self, stage: str | None = None) -> None:
        """Load records from LMDB and build guardrail splits."""
        if self._resolved_lmdb_paths is None:
            raise RuntimeError("prepare_data() must be called before setup()")
        lmdb_paths = self._resolved_lmdb_paths
        records = correctness_data_loading.load_records_from_lmdb(lmdb_paths, self.config.label_type)
        if not records:
            raise ValueError(
                f"no records loaded from {len(self.config.lmdb_paths)} LMDB path(s); "
                f"check that the paths exist and contain benchmark records"
            )
        guardrail_splits = correctness_splits.build_guardrail_splits(records, self.config.split_config)
        # validate splits are usable
        if not guardrail_splits.guardrail_valid:
            raise ValueError(
                "guardrail_valid split is empty after re-splitting; increase the number of "
                "original validation problems or adjust guardrail_valid_fraction"
            )
        valid_has_positive = any(rec.label for rec in guardrail_splits.guardrail_valid)
        valid_has_negative = any(not rec.label for rec in guardrail_splits.guardrail_valid)
        if not valid_has_positive or not valid_has_negative:
            raise ValueError(
                "guardrail_valid split has only one label class; threshold calibration requires "
                "both correct and incorrect attempts in the validation set"
            )
        self._all_records = records
        self._guardrail_splits = guardrail_splits
        logger.info(
            f"correctness datamodule setup: {len(records)} records total, "
            f"train={len(guardrail_splits.guardrail_train)}, "
            f"valid={len(guardrail_splits.guardrail_valid)}, "
            f"test={len(guardrail_splits.guardrail_test)}"
        )
        for subset_name in self.config.subset_names:
            subset_records = self.get_records_for_subset(subset_name)
            problem_ids = {rec.problem_id for rec in subset_records}
            logger.info(f"  {subset_name}: {len(subset_records)} records, {len(problem_ids)} problems")

    @typing.override
    def teardown(self, stage: str | None = None) -> None:
        """Clear loaded data."""
        self._resolved_lmdb_paths = None
        self._all_records = None
        self._guardrail_splits = None

    def get_guardrail_splits(self) -> correctness_splits.GuardrailSplits:
        """Return the full splits object.

        Raises:
            RuntimeError: If called before ``setup()``.
        """
        if self._guardrail_splits is None:
            raise RuntimeError("datamodule not set up, call setup() first")
        return self._guardrail_splits

    def get_records_for_subset(
        self,
        subset_name: str,
    ) -> list[correctness_types.EvalRecord]:
        """Return records for a specific subset.

        Args:
            subset_name: One of ``"guardrail_train"``, ``"guardrail_valid"``, or ``"guardrail_test"``.

        Raises:
            RuntimeError: If called before ``setup()``.
            ValueError: If ``subset_name`` is not a valid subset.
        """
        splits = self.get_guardrail_splits()
        subset_to_records = {
            "guardrail_train": splits.guardrail_train,
            "guardrail_valid": splits.guardrail_valid,
            "guardrail_test": splits.guardrail_test,
        }
        if subset_name not in subset_to_records:
            raise ValueError(f"unknown subset name: {subset_name!r}; expected one of {self.config.subset_names!r}")
        return subset_to_records[subset_name]

    def get_records_for_calibration(self) -> list[correctness_types.EvalRecord]:
        """Return the guardrail_valid records used for threshold calibration.

        Calibration always uses the validation split regardless of which subset is being evaluated,
        so that thresholds are never tuned on test data.

        TODO @@@@@@:
            Accept a calibration settings config (e.g. from ``CorrectnessEvalsConfig``) that
            specifies target class/record balance for the calibration set. This would allow
            studying how robust guardrails are to imperfect calibration datasets (e.g.
            skewed positive/negative ratios, subsampled code types, reduced problem diversity).

        Raises:
            RuntimeError: If called before ``setup()``.
        """
        return self.get_records_for_subset("guardrail_valid")

    def get_all_records(self) -> list[correctness_types.EvalRecord]:
        """Return all records before splitting.

        Raises:
            RuntimeError: If called before ``setup()``.
        """
        if self._all_records is None:
            raise RuntimeError("DataModule not set up. Call setup() first.")
        return self._all_records

    def get_hf_dataset_dict(
        self,
        text_field: str = "model_output",
    ) -> datasets.DatasetDict:
        """Convert guardrail splits into an HF ``DatasetDict``.

        The resulting dataset has columns: ``text``, ``label``, ``sample_id``, ``code_type``
        (same schema as ``ProbeDataModule.get_probe_dataset()``).

        Args:
            text_field: Which ``EvalRecord`` field to use as the ``text`` column.
                Common choices: ``"model_output"``, ``"final_answer"``, ``"expected_output"``.

        Raises:
            RuntimeError: If called before ``setup()``.
            ValueError: If ``text_field`` refers to a None-valued field on any record.
        """
        splits = self.get_guardrail_splits()
        split_map = {
            "guardrail_train": splits.guardrail_train,
            "guardrail_valid": splits.guardrail_valid,
            "guardrail_test": splits.guardrail_test,
        }
        hf_splits: dict[str, datasets.Dataset] = {}
        for split_name, records in split_map.items():
            if not records:
                continue
            texts: list[str] = []
            labels: list[int] = []
            sample_ids: list[str] = []
            code_types: list[str] = []
            for record in records:
                text_value = getattr(record, text_field, None)
                if text_value is None:
                    raise ValueError(
                        f"record {record.sample_id!r} has None for text_field={text_field!r}; "
                        f"choose a field that is always populated"
                    )
                texts.append(str(text_value))
                labels.append(int(record.label))
                sample_ids.append(record.sample_id)
                code_types.append(record.code_type)
            hf_splits[split_name] = datasets.Dataset.from_dict(  # pyright: ignore[reportUnknownMemberType]
                {
                    "text": texts,
                    "label": labels,
                    "sample_id": sample_ids,
                    "code_type": code_types,
                }
            )
        return datasets.DatasetDict(hf_splits)  # pyright: ignore[reportCallIssue,reportArgumentType]

    def get_stats(
        self,
        target_subsets: list[str] | None = None,
    ) -> dict[str, int | float | str]:
        """Return per-subset record counts, positive/negative label counts, and code_type distribution."""
        if self._guardrail_splits is None:
            raise RuntimeError("datamodule not set up, call setup() first")
        stats: dict[str, int | float | str] = {}
        for subset_name in target_subsets or list(self.config.subset_names):
            records = self.get_records_for_subset(subset_name)
            stats[f"{subset_name}/num_records"] = len(records)
            problem_ids = {rec.problem_id for rec in records}
            stats[f"{subset_name}/num_problems"] = len(problem_ids)
            stats[f"{subset_name}/num_positive"] = sum(1 for rec in records if rec.label)
            stats[f"{subset_name}/num_negative"] = sum(1 for rec in records if not rec.label)
            code_type_counts: dict[str, int] = collections.Counter(rec.code_type for rec in records)
            for code_type, count in sorted(code_type_counts.items()):
                stats[f"{subset_name}/code_type/{code_type}"] = count
        return stats

    def get_fingerprint_inputs(self) -> pyine.utils.reprod.FingerprintInputs:
        """Return fingerprint inputs based on config and LMDB file metadata."""
        if self._resolved_lmdb_paths is None:
            raise RuntimeError("prepare_data() must be called before get_fingerprint_inputs()")
        lmdb_paths = self._resolved_lmdb_paths
        metadata_paths = [path / "data.mdb" for path in lmdb_paths if (path / "data.mdb").is_file()]
        return pyine.utils.reprod.FingerprintInputs(
            metadata_paths=metadata_paths,
            extra_content=self.config.model_dump_json().encode(),
        )

    @typing.override
    def train_dataloader(self) -> typing.NoReturn:
        raise NotImplementedError(
            "CorrectnessDataModule does not provide data loaders directly; "
            "use get_records_for_subset() or get_guardrail_splits() instead"
        )

    def val_dataloader(self) -> typing.NoReturn:
        raise NotImplementedError(
            "CorrectnessDataModule does not provide data loaders directly; "
            "use get_records_for_subset() or get_guardrail_splits() instead"
        )

    @typing.override
    def test_dataloader(self) -> typing.NoReturn:
        raise NotImplementedError(
            "CorrectnessDataModule does not provide data loaders directly; "
            "use get_records_for_subset() or get_guardrail_splits() instead"
        )

    def predict_dataloader(self) -> typing.NoReturn:
        raise NotImplementedError(
            "CorrectnessDataModule does not provide data loaders directly; "
            "use get_records_for_subset() or get_guardrail_splits() instead"
        )
